import assert from 'node:assert/strict';
import {WEAPONS} from './data.js';
import {buffs,diminishing,effectiveItemIAS,frameFromEias,calculate,handEias,requiredEquipmentIAS,getBreakpoints} from './core.js';
const s={char:'bar',form:'human',attack:'frenzy',dual:true,iasGear:0,iasMain:0,iasOff:0,cap:'none',other:156,fan:0,frenzy:0,bos:0,how:0,wolf:0,maul:0,purge:0,rancor:0,lethargy:0,freeze:0,decrepify:0,slow:0,cleave:0,mirrored:0,chilled:false,overrideFrames:0};
const scimitar={name:'Scimitar',wsm:-20,type:'oneSwing'};
assert.equal(diminishing(20,0,50),42);
assert.equal(effectiveItemIAS(0),0);
assert.equal(effectiveItemIAS(2996),115);
assert.equal(buffs({...s,how:1}).how,6);
assert.equal(buffs({...s,how:25}).how,30);
assert.equal(buffs({...s,how:150}).how,30);
assert.equal(handEias(s,scimitar,scimitar,'main').raw,176);
assert.equal(calculate(s,scimitar,scimitar).avg,3.5);
assert.equal(frameFromEias(s,scimitar,214),3);
assert.equal(frameFromEias(s,scimitar,355),2);
assert.equal(frameFromEias(s,scimitar,497),1.5);
assert.equal(frameFromEias(s,scimitar,780),1);
assert.equal(calculate({...s,other:780-20,cap:'500'},scimitar,scimitar).avg,1.5);
assert.equal(calculate({...s,other:780-20,cap:'none'},scimitar,scimitar).avg,1);
assert.equal(handEias({...s,iasMain:60,iasOff:50},scimitar,scimitar,'main').item,40);
assert.equal(handEias({...s,iasMain:60,iasOff:50},scimitar,scimitar,'off').item,35);
assert.equal(requiredEquipmentIAS({...s,other:0},scimitar,scimitar,'main',0),0);
const bps=getBreakpoints(s,scimitar);assert(bps.some(x=>x.eias===173&&x.fpa===3.5));assert(bps.some(x=>x.eias===780&&x.fpa===1));
assert(WEAPONS.length>100);console.log('PASS: 18 core scenarios, '+WEAPONS.length+' weapon bases, '+bps.length+' Frenzy breakpoint rows');
